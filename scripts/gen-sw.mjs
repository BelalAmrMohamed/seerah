// Post-build: writes public/sw.js (precache all static assets + all station pages).
import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { createHash } from "node:crypto";

const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : [p];
});
const url = (base, p, prefix) => prefix + relative(base, p).split(sep).map(encodeURIComponent).join("/");
const skip = /\.map$|(^|\/)sw\.js$|\.DS_Store$/;

const pub = walk("public").map((p) => url("public", p, "/")).filter((u) => !skip.test(u));
const next = walk(".next/static").map((p) => url(".next/static", p, "/_next/static/")).filter((u) => !skip.test(u));
const stations = JSON.parse(readFileSync("src/data/stations.json", "utf8"));
const pages = ["/", "/explore/", ...stations.map((s) => `/station/${s.id}/`)];
const assets = [...new Set([...pub, ...next])].sort();
const version = createHash("sha1").update(JSON.stringify([assets, pages])).digest("hex").slice(0, 10);

const sw = `// generated by scripts/gen-sw.mjs — do not edit
const CACHE = "seerah-${version}";
const PAGES = ${JSON.stringify(pages)};
const ASSETS = ${JSON.stringify(assets)};
const NO_CACHE = /^\\/(api|auth)\\//;

self.addEventListener("install", (e) => {
  e.waitUntil((async () => {
    const c = await caches.open(CACHE);
    await Promise.allSettled([...PAGES, ...ASSETS].map((u) => c.add(new Request(u, { cache: "reload" }))));
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (e) => {
  const r = e.request, u = new URL(r.url);
  if (r.method !== "GET" || u.origin !== location.origin || NO_CACHE.test(u.pathname)) return;
  if (r.mode === "navigate") {
    e.respondWith((async () => {
      const c = await caches.open(CACHE);
      try {
        const res = await fetch(r);
        if (res.ok) c.put(r, res.clone());
        return res;
      } catch {
        return (await c.match(r, { ignoreSearch: true })) || (await c.match("/")) || Response.error();
      }
    })());
    return;
  }
  e.respondWith((async () => {
    const c = await caches.open(CACHE);
    const hit = await c.match(r);
    if (hit) return hit;
    try {
      const res = await fetch(r);
      if (res.ok) c.put(r, res.clone());
      return res;
    } catch { return Response.error(); }
  })());
});
`;
writeFileSync("public/sw.js", sw);
console.log(`sw.js: ${pages.length} pages, ${assets.length} assets, cache seerah-${version}`);
